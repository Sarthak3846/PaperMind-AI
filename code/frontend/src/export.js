// Builds a Markdown version of the literature review, including verification flags and references.
const SECTION_TITLES = [
  ['research_overview', 'Research overview'],
  ['cross_paper_synthesis', 'Cross-paper synthesis'],
  ['agreements_and_contradictions', 'Agreements and contradictions'],
  ['research_gaps', 'Research gaps'],
  ['limitations', 'Limitations'],
  ['conclusion', 'Conclusion'],
]

const FLAG = { supported: '', partially_supported: ' ⚠ partially supported', unsupported: ' ✖ UNSUPPORTED', unverified: ' ? unverified' }

export function reviewToMarkdown(result, paperTitle) {
  const refNo = Object.fromEntries((result.references || []).map((r) => [r.chunk_id, r.ref]))
  const line = (s) => {
    const cites = (s.chunk_ids || []).map((c) => refNo[c]).filter(Boolean).map((n) => `[${n}]`).join('')
    return `- ${s.text} ${cites}${s.status ? FLAG[s.status] || '' : s.meta ? ' (scope note)' : ''}`
  }
  const out = [`# Literature review\n`, `**Question:** ${result.question}\n`]
  const r = result.review
  if (!r) return out.join('\n') + '\n_No review was generated._\n'
  const sec = (title, arr) => arr?.length ? [`\n## ${title}\n`, ...arr.map(line)] : []
  out.push(...sec(SECTION_TITLES[0][1], r.research_overview))
  if (r.paper_summaries?.length) {
    out.push('\n## Individual paper summaries\n')
    r.paper_summaries.forEach((p) => out.push(`\n### ${paperTitle(p.paper_id)}\n`, ...p.statements.map(line)))
  }
  SECTION_TITLES.slice(1).forEach(([k, t]) => out.push(...sec(t, r[k])))
  if (result.gaps?.scope_disclaimer) out.push(`\n> ${result.gaps.scope_disclaimer}`)
  out.push('\n## References\n')
  ;(result.references || []).forEach((x) => out.push(`${x.ref}. ${x.title} — ${x.filename}, page ${x.page} (chunk ${x.chunk_id})`))
  const v = result.verification
  if (v) out.push(`\n---\nVerification: ${v.supported} supported, ${v.partially_supported} partially supported, ${v.unsupported} unsupported, ${v.unverified} unverified (of ${v.checked} checked).`)
  out.push(`Generated by PaperMind AI with model ${result.model}, prompt set ${result.prompt_version}. Verify against the sources before citing.`)
  return out.join('\n') + '\n'
}
